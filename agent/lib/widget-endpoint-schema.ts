// The shape of Acquisity's `serializeForemanManifest()` (format 1,
// `apps/web/lib/support/foreman-endpoints/manifest.ts`), and of the endpoint
// list its context route returns per user (ENG-20296).
import { z } from "zod";

const AREA = /^[a-z][a-z0-9-]{0,49}$/;
const SECTION = /^[A-Za-z][A-Za-z0-9_]{0,63}$/;

export const endpointPath = (name: string, version: number) =>
  `/api/internal/foreman/${name}${version > 1 ? `/v${version}` : ""}`;

// Loose throughout, so a field Acquisity adds later passes through untouched.
const manifestSection = z.looseObject({
  meaning: z.string().max(2000),
  name: z.string().regex(SECTION),
  requires: z.array(z.string().max(100)).max(20),
  statuses: z.record(z.string().max(100), z.array(z.string().max(100))),
});

const manifestEndpoint = z
  .looseObject({
    description: z.string().max(4000),
    // Plain JSON Schema for the model; the endpoint validates the input itself.
    inputs: z
      .record(z.string(), z.json())
      .refine((schema) => schema.type === "object", {
        message: "inputs must be an object schema",
      }),
    name: z.string().regex(AREA),
    path: z.string(),
    requires: z.array(z.string().max(100)).max(20),
    sections: z.array(manifestSection).max(50),
    version: z.int().min(1).max(99),
  })
  .refine((entry) => entry.path === endpointPath(entry.name, entry.version), {
    message: "path does not match name and version",
  });

export const endpointManifestSchema = z
  .looseObject({
    endpoints: z.array(manifestEndpoint).max(100),
    formatVersion: z.literal(1),
  })
  .refine(
    (manifest) =>
      new Set(manifest.endpoints.map((entry) => entry.path)).size ===
      manifest.endpoints.length,
    { message: "an endpoint name and version is listed twice" }
  );
export type EndpointManifest = z.infer<typeof endpointManifestSchema>;
export type ManifestEndpoint = z.infer<typeof manifestEndpoint>;

/** One endpoint the context route lists for the asking user. */
export const availableEndpointSchema = z.object({
  name: z.string().regex(AREA),
  path: z.string().max(200),
  sections: z.array(z.string().regex(SECTION)).max(50),
  version: z.int().min(1).max(99),
});
export type AvailableEndpoint = z.infer<typeof availableEndpointSchema>;

/** Keeps the entries that parse, so one malformed entry drops only itself. */
export const parseAvailableEndpoints = (
  value: unknown
): AvailableEndpoint[] | undefined =>
  Array.isArray(value)
    ? value.slice(0, 50).flatMap((entry) => {
        const parsed = availableEndpointSchema.safeParse(entry);
        return parsed.success ? [parsed.data] : [];
      })
    : undefined;

const MARKER = "export const WIDGET_ENDPOINT_MANIFEST";

/**
 * Renders the generated module from the serialized manifest. A new format
 * version or a malformed entry fails the run rather than writing tools from a
 * shape Foreman has not read. When only the commit differs the previous file
 * stands, so a regeneration with nothing new opens no PR.
 */
export function renderEndpointManifest(
  json: string,
  commit: string,
  previous: string,
  format: (source: string) => string
): { changed: boolean; source: string } {
  const manifest = endpointManifestSchema.parse(JSON.parse(json));
  const source = format(
    `// Generated by scripts/widget-endpoint-tools.ts from Acquisity ${commit}. Do not edit by hand; rerun the script.\nimport type { EndpointManifest } from "./widget-endpoint-schema.js";\n\nexport const WIDGET_ENDPOINT_SOURCE = "${commit}";\n\n${MARKER}: EndpointManifest = ${JSON.stringify(manifest)};\n`
  );
  const body = (text: string) => text.slice(text.indexOf(MARKER));
  return previous.includes(MARKER) && body(previous) === body(source)
    ? { changed: false, source: previous }
    : { changed: true, source };
}
